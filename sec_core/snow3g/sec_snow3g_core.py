def snow_3g_feedback(init:int,w:int,s0:int,s2:int,s11:int):
    t0 = (s0 << 8) & 0xFFFFFF00
    t1 = MULalpha((s0 >> 24) & 0xFF)
    t2 = ((s11 >> 8) & 0x00FFFFFF)
    t3 = DIValpha(s11 & 0xFF)
    F = w if init else 0
    s16 = t0 ^ t1 ^ s2 ^ t2 ^ t3 ^ F
    return s16

def snow_3g_lsfr(s16:int,s:list[int]):
    for i in range(15):
        s[i] = s[i+1]
    s[15] = s16 & 0xFFFFFFFF
    #s15 = s[15]
    #s5 = s[5]
    #s0 = s[0]
    return s

def snow_3g_fsm(s5:int,s15:int,r:list[int]):
    w = ((s15 + r[0]) & 0xFFFFFFFF ^ r[1]) & 0xFFFFFFFF
    pre_r0 = (r[1] + (r[2] ^ s5)) & 0xFFFFFFFF

    newR3 = S2(r[1])
    newR2 = S1(r[0])
    newR1 = pre_r0

    r[0] = newR1 & 0xFFFFFFFF
    r[1] = newR2 & 0xFFFFFFFF
    r[2] = newR3 & 0xFFFFFFFF

    return r,w

def snow_3g_core(init:int,w:int,s:list[int],r:list[int]):
    r,w = snow_3g_fsm(s[5],s[15],r)
    s16 = snow_3g_feedback(init,w,s[0],s[2],s[11])
    zt = s[0] ^ w
    s = snow_3g_lsfr(s16,s)
    return zt,w,s,r

