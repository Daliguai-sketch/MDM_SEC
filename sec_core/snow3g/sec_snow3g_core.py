# ----------------------------
# MULx (spec 3.1.1)
# ----------------------------
def MULx(V, c):
    if V & 0x80:
        return ((V << 1) ^ c) & 0xFF
    else:
        return (V << 1) & 0xFF

# ----------------------------
# MULxPOW (spec 3.1.2)
# ----------------------------
def MULxPOW(V, i, c):
    ret = V
    for _ in range(i):
        ret = MULx(ret, c)
    return ret

def MulxPow_iter(V,i,c):
    # for implementation
    a = [1,2,4,8,16,32,64,128]
    for _ in range(i): 
        tmp = a[7]
        a[7] = a[6] ^ (tmp if c>>7 & 0x1 else 0)
        a[6] = a[5] ^ (tmp if c>>6 & 0x1 else 0)
        a[5] = a[4] ^ (tmp if c>>5 & 0x1 else 0)
        a[4] = a[3] ^ (tmp if c>>4 & 0x1 else 0)
        a[3] = a[2] ^ (tmp if c>>3 & 0x1 else 0)
        a[2] = a[1] ^ (tmp if c>>2 & 0x1 else 0)
        a[1] = a[0] ^ (tmp if c>>1 & 0x1 else 0)
        a[0] =        (tmp if c>>0 & 0x1 else 0)
    p = 0
    for i in range(8):
        b = a[i]&V
        t = 0
        for j in range(8):
            t = t ^ (b>>j & 0x1)
        p = p | t<<i
        #print(f"t:{t:02x}, p:{p:02x}")
    return p

# ----------------------------
# MULalpha (spec 3.4.2)
# ----------------------------
def MULalpha(c):
    b0 = MULxPOW(c, 23, 0xA9)
    b1 = MULxPOW(c, 245, 0xA9)
    b2 = MULxPOW(c, 48, 0xA9)
    b3 = MULxPOW(c, 239, 0xA9)

    # for implementation
    b00 = MulxPow_iter(c, 23, 0xA9)
    b01 = MulxPow_iter(c, 245,0xA9)
    b02 = MulxPow_iter(c, 48, 0xA9)
    b03 = MulxPow_iter(c, 239, 0xA9)
    return (b0 << 24) | (b1 << 16) | (b2 << 8) | b3

# ----------------------------
# DIValpha (spec 3.4.3)
# ----------------------------
def DIValpha(c):
    b0 = MULxPOW(c, 16, 0xA9)
    b1 = MULxPOW(c, 39, 0xA9)
    b2 = MULxPOW(c, 6, 0xA9)
    b3 = MULxPOW(c, 64, 0xA9)

    # for implementation
    b00 = MulxPow_iter(c, 16, 0xA9)
    b01 = MulxPow_iter(c, 39, 0xA9)
    b02 = MulxPow_iter(c, 6, 0xA9)
    b03 = MulxPow_iter(c, 64, 0xA9)
    #print(f"DIValpha b2: {c:02x} {b2:02x} {b02:02x}")
    return (b0 << 24) | (b1 << 16) | (b2 << 8) | b3

# ----------------------------
# S1 (spec 3.3.1)
# ----------------------------
def S1(w):
    w0 = (w >> 24) & 0xFF
    w1 = (w >> 16) & 0xFF
    w2 = (w >> 8) & 0xFF
    w3 = w & 0xFF

    s0 = SR[w0]
    s1 = SR[w1]
    s2 = SR[w2]
    s3 = SR[w3]

    r0 = MULx(s0, 0x1B) ^ s1 ^ s2 ^ MULx(s3, 0x1B) ^ s3
    r1 = MULx(s0, 0x1B) ^ s0 ^ MULx(s1, 0x1B) ^ s2 ^ s3
    r2 = s0 ^ MULx(s1, 0x1B) ^ s1 ^ MULx(s2, 0x1B) ^ s3
    r3 = s0 ^ s1 ^ MULx(s2, 0x1B) ^ s2 ^ MULx(s3, 0x1B)

    return (r0 << 24) | (r1 << 16) | (r2 << 8) | r3

# ----------------------------
# S2 (spec 3.3.2)
# ----------------------------
def S2(w):
    w0 = (w >> 24) & 0xFF
    w1 = (w >> 16) & 0xFF
    w2 = (w >> 8) & 0xFF
    w3 = w & 0xFF

    q0 = SQ[w0]
    q1 = SQ[w1]
    q2 = SQ[w2]
    q3 = SQ[w3]

    r0 = MULx(q0, 0x69) ^ q1 ^ q2 ^ MULx(q3, 0x69) ^ q3
    r1 = MULx(q0, 0x69) ^ q0 ^ MULx(q1, 0x69) ^ q2 ^ q3
    r2 = q0 ^ MULx(q1, 0x69) ^ q1 ^ MULx(q2, 0x69) ^ q3
    r3 = q0 ^ q1 ^ MULx(q2, 0x69) ^ q2 ^ MULx(q3, 0x69)

    return (r0 << 24) | (r1 << 16) | (r2 << 8) | r3

