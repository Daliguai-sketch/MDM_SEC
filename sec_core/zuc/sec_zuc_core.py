def ADDM(a, b):
    c = a + b
    return ((c & 0x7FFFFFFF) + (c >> 31)) & 0x7FFFFFFF

def ROT(x, k):
    return ((x << k) | (x >> (32 - k))) & 0xFFFFFFFF

def L1(X):
    return X ^ ROT(X,2) ^ ROT(X,10) ^ ROT(X,18) ^ ROT(X,24)

def L2(X):
    return X ^ ROT(X,8) ^ ROT(X,14) ^ ROT(X,22) ^ ROT(X,30)

def SBOX(X):
    b0 = (X >> 24) & 0xFF
    b1 = (X >> 16) & 0xFF
    b2 = (X >>  8) & 0xFF
    b3 = X & 0xFF
    return (S0[b0] << 24) | (S1[b1] << 16) | (S0[b2] << 8) | S1[b3]

def init_parameters(key, iv, s:List[int],r:List[int]):
    EK_d = [
    0x44D7, 0x26BC, 0x626B, 0x135E, 0x5789, 0x35E2, 0x7135, 0x09AF,
    0x4D78, 0x2F13, 0x6BC4, 0x1AF1, 0x5E26, 0x3C4D, 0x789A, 0x47AC
    ]
    for i in range(4):
        key_word = key[4-1-i]
        iv_word = iv[4-1-i]
        for j in range(4):
            key_byte = (key_word >> 8*(3-j)) & 0xFF
            iv_byte = (iv_word >> 8*(3-j)) & 0xFF
            s_byte = ((key_byte << 23) | EK_d[4*i+j] << 8) | iv_byte
            s[4*i+j] = s_byte
    r[0] = 0
    r[1] = 0

def zuc_lsfr(s:list[int],u):
    v0 = ((s[0]  << 8) | (s[0]  >> (31-8 ))) & 0x7FFFFFFF
    v4 = ((s[4]  <<20) | (s[4]  >> (31-20))) & 0x7FFFFFFF
    v10= ((s[10] <<21) | (s[10] >> (31-21))) & 0x7FFFFFFF
    v13= ((s[13] <<17) | (s[13] >> (31-17))) & 0x7FFFFFFF
    v15= ((s[15] <<15) | (s[15] >> (31-15))) & 0x7FFFFFFF
    f1 = ADDM(s[0], v0)
    f2 = ADDM(f1, v4)
    f3 = ADDM(f2, v10)
    f4 = ADDM(f3, v13)
    f5 = ADDM(f4, v15)
    f6 = ADDM(f5, u)
    for i in range(15):
        s[i] = s[i+1]
    s[15] = f6

    return s

def zuc_br(s0,s2,s5,s7,s9,s11,s14,s15):
    x0 = (((s15 >> 15) & 0xFFFF) << 16) | (s14 & 0xFFFF)
    x1 = ((s11 & 0xFFFF) << 16) | ((s9 >> 15) & 0xFFFF)
    x2 = ((s7 & 0xFFFF) << 16) | ((s5 >> 15) & 0xFFFF)
    x3 = ((s2 & 0xFFFF) << 16) | ((s0 >> 15) & 0xFFFF)

    return x0,x1,x2,x3

def zuc_fsm(x0,x1,x2,r:list[int]):
    w = ((x0 ^ r[0]) + r[1]) & 0xFFFFFFFF
    w1 = (r[0] + x1) & 0xFFFFFFFF
    w2 = (r[1] ^ x2) & 0xFFFFFFFF

    u = L1( ((w1 << 16) & 0xFFFF0000) | ((w2 >> 16) & 0xFFFF) )
    v = L2( ((w2 << 16) & 0xFFFF0000) | ((w1 >> 16) & 0xFFFF) )
    r[0] = SBOX(u)
    r[1] = SBOX(v)

    return r,w

def zuc_core(init:int,w:int,s:list[int],r:list[int]):
    u = 0
    x0,x1,x2,x3 = zuc_br(s[0],s[2],s[5],s[7],s[9],s[11],s[14],s[15])
    r,w = zuc_fsm(x0,x1,x2,r)
    zt = x3 ^ w
    if init:
        u = (w >> 1) & 0x7FFFFFFF
    else:
        u = 0
    s = zuc_lsfr(s,u)
    return zt,w,s,r

